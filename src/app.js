import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import rateLimit from 'express-rate-limit';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import api from './routes/api.js';
import {notFound,errorHandler} from './middleware/errors.js';
const app=express();
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../');
app.use(helmet({crossOriginResourcePolicy:{policy:'cross-origin'}}));
app.use(cors());
app.use(express.json({limit:'20kb'}));
app.use((req,res,next)=>{const start=Date.now();res.on('finish',()=>console.log(JSON.stringify({level:'info',event:'http_request',method:req.method,path:req.path,status:res.statusCode,durationMs:Date.now()-start,time:new Date().toISOString()})));next();});
app.use(express.static(path.join(root,'public')));
app.get('/api/health',(_req,res)=>res.json({success:true,data:{status:'healthy',service:'om-career-hub',timestamp:new Date().toISOString()}}));
app.use('/api',api);
app.use(notFound);
app.use(errorHandler);
export default app;
